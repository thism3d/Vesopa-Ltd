/// Every word the kiosk says, in English and Welsh.
///
/// The venues this is built for are in Wales, and a customer who reads Welsh
/// should be able to order in it end to end -- not find the first screen in
/// Welsh and the payment screen in English. So every sentence on a customer
/// screen comes from here, and the language button on every screen switches
/// the lot.
///
/// THE WELSH IS A DRAFT. It was written by the developer, not a translator, and
/// has to be checked by a Welsh speaker before a venue shows it to the public
/// (tasks.md, P0.6). Keys with no Welsh fall back to the English rather than
/// to a blank, so a missing line is visible and never an empty button.
///
/// So it is HIDDEN: the server's config lists the languages to offer, English
/// only for now, and the language button is drawn only when there are two.
/// Bringing Welsh back is adding 'cy' to LANGUAGES in
/// vesopa_server/src/express_kiosk.js -- no kiosk release -- once somebody who
/// speaks it has read every line below.
///
/// Staff-only screens (setup, settings) are English only.
library;

