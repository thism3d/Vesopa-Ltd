"""Files Vesopa Go shares with the till, copied from the till.

    python vesopa_go/tool/sync_go_shared.py         # bring Go's copies up to the till's
    python vesopa_go/tool/sync_go_shared.py --check # exit 1 if a copy has drifted

Edit these in the till (vesopa_epos), then run this. The till is the
specification for Go (docs/GO_PARITY_PLAN.md): one source, not two that drift.

Two kinds:
  whole   the till's file as it is
  models  the till's data classes only: the part of the file before the class
          named by `stop` (its repository, which reads the till's own providers),
          under the imports given here
"""
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
TILL = REPO / "vesopa_epos"
GO = REPO / "vesopa_go"

SHARED = [
    {"kind": "whole", "till": "lib/data/till_permissions.dart", "go": "lib/data/till_permissions.dart"},
    # The engine as it is, reading Go's own MixMatchDeal and OrderLine
    # (lib/data/mix_match_types.dart) instead of the till's database rows.
    {
        "kind": "whole",
        "till": "lib/data/mix_match_engine.dart",
        "go": "lib/data/mix_match_engine.dart",
        "swap": [("import 'local/database.dart';", "import 'mix_match_types.dart';")],
    },
    {
        "kind": "models",
        "till": "lib/data/screens.dart",
        "go": "lib/data/screen_set.dart",
        "stop": "class ScreensRepository",
        "head": (
            "// GENERATED by vesopa_go/tool/sync_go_shared.py from vesopa_epos/lib/data/screens.dart\n"
            "// (the screen-programming model, without the till's repository). Edit it in the till.\n"
            "\n"
            "import 'package:flutter/material.dart' show BoxFit, Color;\n"
            "\n"
            "import '../config/constants.dart' as go_config;\n"
            "\n"
            "/// The till's `Api.resolvedBase`, as Go knows it: where pictures are served from.\n"
            "abstract final class Api {\n"
            "  static String get resolvedBase => go_config.apiBase;\n"
            "}\n"
        ),
    },
]


def build(item):
    till = (TILL / item["till"]).read_bytes()
    if item["kind"] == "whole":
        for old, new in item.get("swap", []):
            assert old.encode() in till, (item["till"], old)
            till = till.replace(old.encode(), new.encode())
        return till
    text = till.decode("utf-8").replace("\r\n", "\n")
    body = text[: text.index(item["stop"])]
    # Everything after the till's imports.
    lines = body.split("\n")
    last_import = max(i for i, l in enumerate(lines) if l.startswith("import "))
    rest = "\n".join(lines[last_import + 1 :]).strip("\n")
    # The doc comment of the stopped class, left dangling: cut a trailing /// run.
    out = rest.split("\n")
    while out and out[-1].lstrip().startswith("///"):
        out.pop()
    return (item["head"] + "\n" + "\n".join(out).rstrip() + "\n").encode("utf-8")


drift = []
for item in SHARED:
    want = build(item)
    go = GO / item["go"]
    if not go.exists() or go.read_bytes() != want:
        drift.append(item["go"])
        if "--check" not in sys.argv:
            go.write_bytes(want)
for rel in drift:
    print(("drifted: " if "--check" in sys.argv else "copied: ") + rel)
sys.exit(1 if drift and "--check" in sys.argv else 0)
