"""Write the legal pages (tool/legal_content.py) into each site in its own look.

    python tool/make_legal_pages.py

  vesopaepos.com      vesopa_web/views/legal/<slug>.ejs, served by src/routes/legal.js
                      (/refund is replaced; /terms and /privacy keep their own pages)
  vesopasoftware.com  vesopasoftware/site/<slug>.html and site/apps/<app>.html
  go.vesopa.com       vesopa_go/web/site/<slug>/index.html

Run it again after changing legal_content.py; it only writes files.
"""
import html
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tool"))
import legal_content as L  # noqa: E402

CSS = """
.legal-list{padding-left:1.1rem}.legal-list li{margin:.35rem 0}
.legal-table{border-collapse:collapse;width:100%;margin:1rem 0 1.5rem;font-size:.98rem}
.legal-table th,.legal-table td{border-bottom:1px solid rgba(127,127,127,.25);padding:.6rem .5rem;text-align:left;vertical-align:top}
.legal-table th{width:34%;font-weight:600}
.legal-nav{display:flex;flex-wrap:wrap;gap:.4rem .9rem;margin:2.2rem 0 0;padding-top:1rem;border-top:1px solid rgba(127,127,127,.25);font-size:.92rem}
"""


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.encode("utf-8"))


def nav(prefix=""):
    links = [("legal", "All policies"), ("terms", "Terms"), ("privacy", "Privacy"), ("refund", "Refunds"),
             ("payments-security", "Payments"), ("acceptable-use", "Acceptable use"), ("complaints", "Complaints"),
             ("international", "International"), ("company", "Company")]
    return '<nav class="legal-nav" aria-label="Policies">' + "".join(
        f'<a href="{prefix}/{s}">{t}</a>' for s, t in links) + "</nav>"


# ---- vesopaepos.com (EJS inside the site's header and footer) -----------------------

def vesopaepos():
    views = ROOT / "vesopa_web" / "views" / "legal"
    for p in L.PAGES:
        write(views / f"{p['slug']}.ejs", f"""<%- include('../partials/header') %>
<%# Generated by tool/make_legal_pages.py from tool/legal_content.py: edit there. %>
<style>{CSS}
.legal-doc{{max-width:860px;margin:0 auto;padding:56px 20px 72px;line-height:1.65}}
.legal-doc h1{{font-size:36px;margin:0 0 6px}}.legal-doc h2{{font-size:22px;margin:32px 0 8px}}
.legal-doc .asof{{opacity:.7;margin:0 0 24px}}.legal-doc ul,.legal-doc ol{{padding-left:1.2rem}}
</style>
<main class="legal-doc">
  <p class="vh-eyebrow">Legal</p>
  <h1>{html.escape(p['title'])}</h1>
  <p class="asof">Last updated {L.UPDATED}</p>
  {p['body']}
  {nav()}
</main>
<%- include('../partials/footer') %>
""")
    print("vesopaepos.com:", len(L.PAGES), "pages")


