def vesopasoftware():
    site = ROOT / "vesopasoftware" / "site"
    for p in L.PAGES:
        body = f"""<span class="eyebrow">Legal</span>
<h1>{html.escape(p['title'])}</h1>
<p class="stamp">Last updated {L.UPDATED}</p>
<p class="lead">{html.escape(p['summary'])}</p>
{p['body']}
{nav()}
"""
        write(site / f"{p['slug']}.html", vs_head(p["title"], p["summary"], f"/{p['slug']}") + body + VS_FOOT)
    for a in L.APPS:
        write(site / "apps" / f"{a['slug']}.html",
              vs_head(f"{a['name']} app", f"Trader information, privacy and terms for the {a['name']} app.", f"/apps/{a['slug']}")
              + app_page(a) + nav() + VS_FOOT)
    print("vesopasoftware.com:", len(L.PAGES), "pages and", len(L.APPS), "app pages")


# ---- go.vesopa.com (its .doc layout) ------------------------------------------------------

