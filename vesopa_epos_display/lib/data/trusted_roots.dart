/// The two roots, for a test that builds its own context.
const pemsForTest = [_isrgRootX1, _isrgRootX2];

/// Call once at start-up, before the first request.
void trustOurServerRoots() {
  for (final pem in const [_isrgRootX1, _isrgRootX2]) {
    try {
      SecurityContext.defaultContext.setTrustedCertificatesBytes(utf8.encode(pem));
    } on Object catch (_) {
      // Already trusted (the machine has it), or a platform whose default
      // context cannot be changed: either way the system roots still apply.
    }
  }
}

/// What a failed request means, in words for the person at the screen.
///
/// Null when the error is not one of these, so the caller keeps its own.
String? connectionProblem(Object error) {
  if (error is HandshakeException || error is TlsException) {
    return 'This computer could not check the back office\'s security '
        'certificate. Check the date and time on this computer are right, '
        'then try again.';
  }
  if (error is SocketException) {
    return 'This computer is not connected to the internet, or the back '
        'office cannot be found from this network. Check the network cable '
        'or Wi-Fi, then try again.';
  }
  if (error is TimeoutException) {
    return 'The back office took too long to answer. Check the internet '
        'connection, then try again.';
  }
  return null;
}
